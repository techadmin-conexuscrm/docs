"""LAB ONLY. sweep.json (amd-sweep.py) -> sweep-results.md
  python3 report-sweep.py <sweep.json> <out.md>"""
import json, sys
d = json.load(open(sys.argv[1])); o = []
P = ["silence_threshold", "between_words_silence", "initial_silence", "after_greeting_silence",
     "maximum_number_of_words", "greeting", "total_analysis_time"]
short = dict(silence_threshold="thresh", between_words_silence="bws", initial_silence="init_sil",
             after_greeting_silence="ags", maximum_number_of_words="words", greeting="greeting",
             total_analysis_time="total")
o.append("# AMD parameter sweep: results\n")
o.append("Generated by `report-sweep.py` from `amd-sweep.py`'s output. Strategy and reading guide: `AMD-STRATEGY.md`.\n")
o.append(f"- settings tried: **{d['cells_total']:,}** (the grid below)")
o.append(f"- right on every clip at nominal level and speed: **{d['cells_pass_nominal']:,}**")
o.append(f"- of those, no person harmed (MACHINE or a drop on a person) in any of the {d['variants_per_clip']} level/speed variants of any clip: **{d['cells_pass_nominal_and_no_person_harmed_in_any_variant']:,}**")
o.append(f"- right on every clip in every variant: **{d['cells_pass_all_variants']:,}**")
for s in d["stress_clips"]:
    o.append(f"- with stress clip `{s}` also required at nominal: {d.get('cells_pass_nominal_with_' + s, 0):,}")
o.append(f"- run time {d['seconds']} s\n")
o.append("## Values that appear in at least one setting that is right on every clip (nominal)\n")
for k, v in d["ranges_pass_nominal"].items(): o.append(f"- `{k}`: {', '.join(map(str, v))}")
def row(c):
    return "| " + " | ".join(str(c[k]) for k in P) + f" | {c['person_harming_variants']} | {c['worst_clip_variants']}/{d['variants_per_clip']} | {c['neighbours_passing']}/14 | {c['total_variant_passes']} |"
hdr = "| " + " | ".join(short[k] for k in P) + " | person-harming variants | worst clip | neighbours | total |\n|" + "---|" * (len(P) + 4)
o.append("\n## Top 20 settings (ranked: no person harmed, then worst clip, then neighbours, then total)\n")
o.append(hdr); o += [row(c) for c in d["top"]]
o.append("\nWeakest clips of the top setting (variants passed, out of %d): %s\n" % (d["variants_per_clip"], ", ".join(f"`{k}` {v}" for k, v in d["top"][0]["weakest"].items()) or "none"))
o.append("## Best setting for each silence_threshold\n"); o.append(hdr)
o += [row(c) for c in d["best_per_silence_threshold"] if c]
o.append("\n## Best setting for each between_words_silence\n"); o.append(hdr)
o += [row(c) for c in d["best_per_between_words_silence"] if c]
if "chosen" in d:
    o.append("\n## The recommended setting (picked from the top band, AMD-STRATEGY.md 5.2)\n")
    o.append(hdr); o.append(row(d["chosen"]))
if "margins" in d:
    o.append("\n## Margins of the recommended setting: move one dial, hold the rest\n")
    o.append("`ok` = right on every clip at nominal level and no person harmed in any variant; `nominal only` = right at nominal but a person is harmed in some level/speed variant; `fails` = wrong on some clip at nominal.\n")
    for k, v in d["margins"].items():
        o.append(f"- `{k}`: " + ", ".join(f"{a} {b}" for a, b in v.items()))
if "avmd_misses" in d:
    o.append("\n## mod_avmd in the variants (from avmd-harness, not counted against the settings)\n")
    o.append("- beep clips where avmd heard no beep (of 18 variants): " + (", ".join(f"`{k}` {v}" for k, v in d["avmd_misses"].items() if v) or "none"))
    o.append("- clips with no beep where avmd heard one: " + (", ".join(f"`{k}` {v}" for k, v in d["avmd_false"].items() if v) or "none"))
for label, cfg in d["configs"].items():
    o.append(f"\n## {label}\n")
    o.append("`" + " ".join(f"{k}={cfg['params'][k]}" for k in P) + "`\n")
    o.append("| clip | expect | verdict | cause | at s | strategy does | ok | variants ok | max voice ms | words | longest pause ms | variant failures |\n|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in cfg["rows"]:
        o.append(f"| `{r['clip']}`{' (stress)' if r['stress'] else ''} | {r['expect']} | {r['verdict']} | {r['cause']} | {r['t']} | {r['action']} | {'yes' if r['ok'] else 'NO: ' + r['why']} | {r['variants_ok']} | {r['max_voice_ms']} | {r['max_words']} | {r['max_gap_ms']} | {'; '.join(r['variant_failures'])} |")
o.append("\n## The drop's wait after the avmd beep event, every beep clip x every variant\n")
o.append("Drop must start after the last beep has ended and within 3 s of it.\n")
o.append("| wait | right | timed out (fell through) | earliest vs beep end s | latest s | failures (clip, s after beep end, timed out) |\n|---|---|---|---|---|---|")
for k, v in d["wfs"].items():
    o.append(f"| {k} | {v['ok']}/{v['of']} | {v.get('timed_out', '')} | {v['min_after']} | {v['max_after']} | {v['failures']} |")
open(sys.argv[2], "w").write("\n".join(o) + "\n")
